/**
 * Write the plugin's stylesheet from the one pterodocs already publishes.
 *
 * The plugin used to carry a second design meaning to look like the first. Two
 * of anything that must agree will drift, and this pair drifted into stacking:
 * a site with the plugin installed got both, each padding a different element,
 * so the documentation sat further in than the same documentation without it.
 *
 * So there is one design now, `packages/core/src/render/stylesheet.ts`, and
 * this copies it out. The `{p}` placeholder is left in: the class prefix is a
 * per-site setting, so PHP puts it in at enqueue time.
 *
 * Run after `npm run build` at the repository root — the template is read from
 * core's build output rather than parsed out of its source, so that renaming or
 * reformatting the template cannot quietly produce a stale copy here.
 */

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const core = path.join(here, '..', '..', '..', 'core', 'lib', 'render', 'index.js');

if (!fs.existsSync(core)) {
  console.error(
    `Cannot find ${path.relative(process.cwd(), core)}.\n` +
      'Run `npm run build` at the repository root first: this reads the stylesheet\n' +
      'from core\'s build output so the two cannot disagree.',
  );
  process.exit(1);
}

const { STYLESHEET_TEMPLATE } = await import(pathToFileURL(core).href);

if (typeof STYLESHEET_TEMPLATE !== 'string' || !STYLESHEET_TEMPLATE.includes('{p}')) {
  console.error('core exported no usable stylesheet template.');
  process.exit(1);
}

const header = `/*
 * Generated by tools/vendor-stylesheet.mjs. Do not edit.
 *
 * This is the stylesheet pterodocs publishes with a page, verbatim, with the
 * class prefix left as {p} for PHP to fill in. Change it in
 * packages/core/src/render/stylesheet.ts and run \`npm run vendor\`.
 *
 * Anything the plugin adds that pterodocs cannot — the copy button, the
 * collapsible tree, line numbers — lives in plugin.css instead.
 */
`;

const out = path.join(root, 'assets', 'css', 'docs.css');
fs.writeFileSync(out, `${header}${STYLESHEET_TEMPLATE.trimStart()}`, 'utf8');

const bytes = fs.statSync(out).size;
console.log(`wrote assets/css/docs.css — ${bytes} bytes, from core's stylesheet`);
